const path = require("path");
const fs = require("fs");
const createJiti = require("jiti");

// 1. Load .env.local into process.env if not set
if (!process.env.AUTH_SECRET) {
  const envPath = path.resolve(__dirname, "../.env.local");
  if (fs.existsSync(envPath)) {
    const content = fs.readFileSync(envPath, "utf-8");
    for (const line of content.split("\n")) {
      const match = line.trim().match(/^AUTH_SECRET\s*=\s*["']?([^"'\r\n]+)["']?/);
      if (match) {
        process.env.AUTH_SECRET = match[1];
        break;
      }
    }
  }
}

if (!process.env.AUTH_SECRET) {
  console.error("FAIL: AUTH_SECRET must be set in process.env or .env.local");
  process.exit(1);
}

const jiti = createJiti(path.resolve(__dirname, "smoke-runner.js"), {
  alias: {
    "server-only": path.resolve(__dirname, "empty.js"),
    "@": path.resolve(__dirname, "../src"),
  },
});

const { getPageByPath, getDbItem } = jiti("../src/lib/db");
const { createSessionToken, setCliSessionToken } = jiti("../src/lib/auth");
const { savePageV2Action } = jiti("../src/app/admin/actions");
const { runIndexReadiness } = jiti("../scripts/index-readiness");

async function runEditSurvivesTest() {
  console.log("======================================================================");
  console.log("  PROTECT EDITOR WORK PROOF TEST (STEP 5)");
  console.log("======================================================================\n");

  // Step 1: Use existing admin account from the store (USER:usr_initial_admin)
  console.log("[Auth] Retrieving existing admin account USER:usr_initial_admin from store...");
  const adminUser = await getDbItem("USER", "usr_initial_admin");
  if (!adminUser || !adminUser.id) {
    throw new Error("FAIL: USER:usr_initial_admin not found in content store.");
  }

  const adminSession = {
    userId: adminUser.id,
    email: adminUser.email,
    role: adminUser.role,
    name: adminUser.name,
  };
  console.log(`[Auth] Using existing admin account: ${adminSession.name} (${adminSession.userId})`);

  const token = await createSessionToken(adminSession);
  setCliSessionToken(token);
  console.log("[Auth] CLI admin session token established successfully.\n");

  // Step 2: Fetch target test page (/seo/local-seo)
  const testPath = "/seo/local-seo";
  console.log(`[Test] Fetching original test page: ${testPath}...`);
  const originalPage = await getPageByPath(testPath);
  if (!originalPage) {
    throw new Error(`Test page ${testPath} not found in store.`);
  }

  // Deep clone original page for restoration
  const originalSnapshot = JSON.parse(JSON.stringify(originalPage));
  console.log(`[Test] Original page captured (${originalSnapshot.sections.length} sections).\n`);

  // Step 3: Modify one block on the test page via savePageV2Action
  const testEditParagraph = "PROOF TEST EDIT: This block was customized by an editor in Admin Studio and must never be regenerated by scripts.";
  const modifiedPage = JSON.parse(JSON.stringify(originalSnapshot));
  
  // Edit the overview section
  const targetSectionIndex = modifiedPage.sections.findIndex((s) => s.type === "richText" || s.id.includes("overview"));
  if (targetSectionIndex === -1) {
    throw new Error("Could not find target overview section on test page.");
  }

  console.log(`[Test] Editing section at index ${targetSectionIndex} (id: ${modifiedPage.sections[targetSectionIndex].id})...`);
  modifiedPage.sections[targetSectionIndex].content.paragraphs = [testEditParagraph];
  modifiedPage.sections[targetSectionIndex].title = "Custom Editor Section [Human Edited]";
  modifiedPage.sections[targetSectionIndex].generated = false;

  console.log("[Test] Saving page via savePageV2Action (simulating Admin Studio save)...");
  const saveResult = await savePageV2Action(modifiedPage);
  if (!saveResult.success) {
    throw new Error(`savePageV2Action failed: ${saveResult.error}`);
  }
  console.log(`[Test] Page saved successfully. savedInStudioAt: ${saveResult.page.savedInStudioAt}`);
  console.log(`[Test] Updated by: ${saveResult.page.updatedBy}\n`);

  // Verify save occurred in store
  const savedInStore = await getPageByPath(testPath);
  const savedParagraph = savedInStore.sections[targetSectionIndex]?.content?.paragraphs?.[0];
  if (savedParagraph !== testEditParagraph) {
    throw new Error("Saved paragraph does not match test edit in store.");
  }
  console.log("[Test] Verified: Custom editor block is live in the content store.\n");

  // Step 4: Re-run index-readiness.ts --apply
  console.log("[Test] Running index-readiness audit with --apply mode...");
  await runIndexReadiness(true);
  console.log("[Test] index-readiness --apply completed.\n");

  // Step 5: Prove the edit survived!
  console.log(`[Test] Fetching ${testPath} from store to verify survival...`);
  const postAuditPage = await getPageByPath(testPath);
  const postAuditSection = postAuditPage.sections[targetSectionIndex];
  const postAuditParagraph = postAuditSection?.content?.paragraphs?.[0];

  console.log(`[Test] Post-audit section title: "${postAuditSection?.title}"`);
  console.log(`[Test] Post-audit paragraph: "${postAuditParagraph}"`);

  if (postAuditParagraph !== testEditParagraph) {
    throw new Error("FAIL: Custom editor block was overwritten during index-readiness run!");
  }
  console.log("\n>>> SUCCESS: Custom editor block SURVIVED index-readiness --apply without being overwritten! <<<\n");

  // Step 6: Restore page ONLY through savePageV2Action (honest audit trail, no manual field resets)
  console.log("[Restore] Restoring original page content ONLY via savePageV2Action...");
  const restorePagePayload = JSON.parse(JSON.stringify(originalSnapshot));
  const restoreResult = await savePageV2Action(restorePagePayload);
  if (!restoreResult.success) {
    throw new Error(`Restore failed: ${restoreResult.error}`);
  }
  console.log(`[Restore] Page restored via savePageV2Action. savedInStudioAt: ${restoreResult.page.savedInStudioAt}`);
  console.log(`[Restore] Audit trail updatedBy: ${restoreResult.page.updatedBy}`);

  // Re-run index-readiness to verify everything stays consistent
  console.log("[Restore] Running index-readiness --apply to verify consistent state...");
  await runIndexReadiness(true);

  const finalCheckPage = await getPageByPath(testPath);
  console.log(`[Restore] Final check: ${testPath} section title: "${finalCheckPage.sections[targetSectionIndex].title}"`);
  console.log(`[Restore] Restored paragraph: "${finalCheckPage.sections[targetSectionIndex].content.paragraphs[0].slice(0, 70)}..."`);
  console.log("\n======================================================================");
  console.log("  STEP 5 PROOF TEST PASSED: Editor work is 100% protected!");
  console.log("======================================================================\n");
}

runEditSurvivesTest().catch((err) => {
  console.error("FATAL PROOF TEST ERROR:", err);
  process.exit(1);
});
